def _measured_rows(rows):
    keys = ("BLOCK_SIZE_M", "BLOCK_SIZE_N", "GROUP_SIZE_M", "num_warps", "num_stages")

    def config(c):
        # An optional sixth field overrides route_blocks for the row.
        extra = {"route_blocks": c[5]} if len(c) == 6 else {}
        return dict(zip(keys, c[:5], strict=True), BLOCK_SIZE_K=128, **extra)

    return [tuple([limit] + [config(c) for c in (fc1, fc2)]) for limit, fc1, fc2 in rows]


# (CC major, CC minor, SM count) -> (E_local, H, I, top_k) -> token limit, FC1, FC2.
TABLE = {
    device: {(e, 2048, 512, 8): _placeholder_rows(e, device[:2]) for e in (256, 128)}
    for device in ((8, 9, 128), (9, 0, 132), (12, 0, 170), (12, 0, 188), (12, 1, 48))
}
for _device, _experts in MEASURED.items():
    for _shape, _rows in _experts.items():
        TABLE.setdefault(_device, {})[_shape] = _measured_rows(_rows)


def selection(device_class, num_tokens, num_experts, hidden=2048, intermediate=512, top_k=8):
    if not isinstance(num_tokens, int) or num_tokens < 0:
        raise ValueError("num_tokens must be a nonnegative integer")
    shape = (num_experts, hidden, intermediate, top_k)
    for limit, fc1, fc2 in TABLE.get(device_class, {}).get(shape, ()):
        if num_tokens <= limit:
            if fc1["BLOCK_SIZE_M"] != fc2["BLOCK_SIZE_M"]:
                raise ValueError("FC1 and FC2 must share BLOCK_SIZE_M")
            if any(c["BLOCK_SIZE_K"] != 128 for c in (fc1, fc2)):
                raise ValueError("block-FP8 configs require BLOCK_SIZE_K = 128")
            return _route_config(fc1, fc2, num_tokens * top_k)
    config = block_fp8_moe_config(
        num_tokens, num_experts, 2 * intermediate, hidden, top_k, capability=device_class[:2]
    )
    return _route_config(config, config, num_tokens * top_k)


def _route_config(fc1, fc2, routes):
    # A table row may explicitly enable/disable this independently of its limit.
    default = routes <= 64 and fc1["BLOCK_SIZE_M"] == 16
    route_blocks = fc1.get("route_blocks", fc2.get("route_blocks", default))
    if fc2.get("route_blocks", route_blocks) != route_blocks:
        raise ValueError("FC1 and FC2 must share route_blocks")
    return tuple(dict(c, route_blocks=route_blocks) for c in (fc1, fc2))
