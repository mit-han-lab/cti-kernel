"""Per-device, exact-shape FC1/FC2 launch policy for block-FP8 MoE."""

from .moe_impl import block_fp8_moe_config


def _placeholder_rows(e, capability):
    rows = []
    for limit in (8, e // 2, 4096):
        config = block_fp8_moe_config(limit, e, 1024, 2048, 8, capability=capability)
        if limit == 8:
            config["route_blocks"] = True
        rows.append((limit, config.copy(), config.copy()))
    return rows


