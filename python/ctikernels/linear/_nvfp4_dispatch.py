_devices: dict[torch.device, tuple[str, tuple[int, int]]] = {}


# Rows above this bucket reuse each plan's last entry (see ``_entry``).
LAST_BUCKET = max(
    (entry[0] for plans in GATED.values() for plan in plans.values() for entry in plan),
    default=1,
)


def _device_type(device: torch.device) -> tuple[str, tuple[int, int]]:
    if device not in _devices:
        _devices[device] = (
            torch.cuda.get_device_name(device),
            tuple(torch.cuda.get_device_capability(device)),
        )
    return _devices[device]


def _entry(plan: tuple, rows: int) -> tuple:
    bucket = 1 << max(rows - 1, 0).bit_length()
    for entry in plan:
        if bucket <= entry[0]:
            return entry
    return plan[-1]


def small_fits(config: Small, rows: int, n: int, k: int, *, gated: bool) -> bool:
    """Whether the Triton configuration serves ``rows`` of an ``[n, k]`` weight."""
    return (
        rows <= SMALL_ROWS
        and k % (config.splits * config.block_k) == 0
        and (not gated or config.block_n % 32 == 0)
    )


def cute_fits(config: Cute, device, rows: int, n: int, k: int, *, gated: bool) -> bool:
    """Validate metadata and availability without compiling or allocating device storage."""
    if not 1 <= rows <= 32 or n < 1 or (gated and n % 64):
        return False
    from . import _nvfp4_cute_small

    if not _nvfp4_cute_small.available(device):
        return False
    try:
        validated = config.config()
        validated.validate(k)
        if gated and validated.n_tile < 32:
            return False
    except (TypeError, ValueError):
        return False
    return True


def _entries(plan, rows):
    first = _entry(plan, rows)
    return plan[plan.index(first) :]


def linear_plan(device: torch.device, n: int, k: int) -> FlashInfer | Config:
    """FlashInfer for every M where it supports the shape, else the default QuACK tile."""
    from ._nvfp4_flashinfer import supports_shape

    return FlashInfer() if supports_shape(n, k, _device_type(device)[1]) else DEFAULT


def gated_plan(
    device: torch.device,
    h: int,
    i: int,
    rows: int,
    *,
    allow_cute: bool = True,
    shared_globals: bool = True,
) -> tuple[str, Config | Small | FlashInfer | Cute]:
    """Independent gate/up globals skip FlashInfer entries: one CUTLASS GEMM takes one
    alpha, so they need two GEMMs plus an up-alpha product (5 launches). Qwen3.8-27B,
    unequal globals (2026-10-17): QuACK fused beat that at M<=32 on RTX 5090 (87.0 vs
    92.8 us at M=32) and GB10 (446.6 vs 453.9 us at M=1, 450.9 vs 477.1 at M=32)."""
    plan = GATED.get(_device_type(device), {}).get((h, i))
    if plan is None:
        return FUSED, DEFAULT
    for _, path, config in _entries(plan, rows):
        if isinstance(config, FlashInfer) and not shared_globals:
            continue
        if path == TRITON and not small_fits(config, rows, 2 * i, h, gated=True):
            continue
        if isinstance(config, Cute) and (
            path != CUTE
            or not allow_cute
            or not cute_fits(config, device, rows, 2 * i, h, gated=True)
        ):
            continue
        return path, config
    return FUSED, DEFAULT


def uses_cute(device: torch.device, shape: tuple[int, int]) -> bool:
    """Whether this gated shape has a CuTe bucket; metadata only, for construction-time packing."""
    return any(
        isinstance(entry[-1], Cute) for entry in GATED.get(_device_type(device), {}).get(shape, ())
    )


def uses_flashinfer(
    device: torch.device, shape: tuple[int, int], *, gated: bool, shared_globals: bool = True
) -> bool:
    """Whether any bucket of this shape can choose FlashInfer; metadata only."""
    if not gated:
        from ._nvfp4_flashinfer import supports_shape

        return supports_shape(*shape, _device_type(device)[1])
    if not shared_globals:
        return False
    return any(
        isinstance(entry[-1], FlashInfer)
        for entry in GATED.get(_device_type(device), {}).get(shape, ())
    )
