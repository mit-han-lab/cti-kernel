"""NVFP4 plans per device and weight shape.

Linear has no table: ``linear_plan`` picks FlashInfer wherever it supports the shape (every M),
else the default QuACK tile.

Gated plans map batch-size buckets (the next power of two of the row count) to the configuration
measured fastest under CUDA-graph timing; batches past the last bucket take its entry, and
unlisted shapes use ``DEFAULT``. A configuration is a QuACK tile ``Config``, a FlashInfer CUTLASS
``FlashInfer`` marker (``UNFUSED`` only), for at most ``SMALL_ROWS`` rows a Triton ``Small`` one,
or a CuTe ``Cute`` plan for at most 32 rows. Invalid small-M plans fall through to subsequent
compatible entries, then ``DEFAULT``. Each entry also names the path: ``"quack-fused"`` (SiLU * up
and quantization in the QuACK epilogue), ``"quack-unfused"`` (BF16 projection, then the Triton
SiLU * up quantizer), ``"triton"`` (the small-batch Triton GEMM with the same epilogue) or
``"cute"``. Generated by ``benchmark/kernel_tuning/nvfp4_dispatch.py`` from
``benchmark/kernel_tuning/nvfp4.py`` runs. The Triton GEMM uses per-operation arrival counters:
one object's calls and graph replays must run in order on one stream.
"""

from __future__ import annotations

from typing import NamedTuple

import torch

from ._nvfp4_quack import DEFAULT, Config

FUSED = "quack-fused"
UNFUSED = "quack-unfused"
TRITON = "triton"
CUTE = "cute"
SMALL_ROWS = 64


class Small(NamedTuple):
    """A Triton small-batch GEMM configuration: K splits, tile sizes, launch shape, and whether
    the activation is quantized by a separate kernel first (else inside the GEMM). With more
    than one split, the last program to arrive at each column tile's counter sums the FP32
    partials in split order and applies the epilogue in the same launch."""

    splits: int
    block_n: int
    block_k: int
    warps: int
    stages: int
    prequantize: bool


class FlashInfer(NamedTuple):
    """FlashInfer CUTLASS NVFP4 GEMM (UNFUSED only for gated projections)."""


class Cute(NamedTuple):
    """Small-M CuTe plan stored without importing the optional DSL."""

    n_tile: int = 64
    k_tile: int = 512
    stages: int = 2
    split_k: int = 8
    warps: int = 3
    max_slice_k: int = 3072
    ctas_per_sm: int = 1
    reduce_mode: str = "global"
    qwarps: int = 1
    a_stages: int = 4
    pdl: bool = False

    def config(self):
        from ._nvfp4_cute_small import Config

        return Config(**self._asdict())


