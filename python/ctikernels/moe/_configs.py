# The two RTX 5090 M=8192 entries that SGLang's sweep took with TMA run without it here (our
# grouped GEMM has no TMA path); every other key is a launch parameter of that kernel.
_KEYS = ("BLOCK_SIZE_M", "BLOCK_SIZE_N", "BLOCK_SIZE_K", "GROUP_SIZE_M", "num_warps", "num_stages")


def lookup(kind, experts, inter, rows, phase):
    """Nearest M key; ties choose the smaller key. Return a copy for overrides."""
    if phase not in ("up", "down"):
        raise ValueError("phase must be up or down")
    table = TUNED.get(kind, {}).get((experts, inter), {}).get(phase, {})
    if not table:
        return None
    entry = table[min(table, key=lambda key: (abs(key - rows), key))]
    return {key: entry[key] for key in _KEYS if key in entry}
