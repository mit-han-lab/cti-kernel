@pytest.mark.parametrize("counter,key,expected", KATS)
def test_published_kat(counter, key, expected):
    assert philox4x32(counter, key) == expected


@pytest.mark.parametrize("cursor,domain,i,expected", GOLDEN)
def test_abi_golden(cursor, domain, i, expected):
    assert K1_RNG_ABI_VERSION == 1
    assert words(SEED, cursor, domain, i) == expected
    assert uniform(SEED, cursor, domain, i) == (expected[0] >> 8) * 2**-24
    assert 0 <= uniform(SEED, cursor, domain, i) < 1
    assert categorical([0.25] * 4, uniform(SEED, cursor, domain, i)) == expected[0] >> 30
    if domain < ORDINARY_NAMESPACE:
        assert words(SEED, cursor, ORDINARY_NAMESPACE, 0) != expected


def test_full_width_seed():
    assert words(0xFFFFFFFFFFFFFFFF, 4294967319, 1, 0) == (
        1770347725,
        1331038218,
        1525943768,
        2235050435,
    )


@pytest.mark.parametrize("seed,cursor", [(-1, 0), (0, -1), (2**64, 0), (0, 2**63)])
def test_no_wrap(seed, cursor):
    with pytest.raises(ValueError):
        words(seed, cursor, 1, 0)
